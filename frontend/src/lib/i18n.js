const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState('en');

  useEffect(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('suraksha_lang');
      if (saved && LANGUAGES.some(l => l.code === saved)) {
        queueMicrotask(() => setLang(saved));
      }
    }
  }, []);

  const changeLang = useCallback((code) => {
    setLang(code);
    if (typeof window !== 'undefined') {
      localStorage.setItem('suraksha_lang', code);
      document.cookie = `suraksha_lang=${code}; path=/; max-age=31536000; SameSite=Lax`;
    }
  }, []);

    const t = useCallback((key) => {
    if (!key) return '';
    const localized = translations[lang]?.[key] || translations.en?.[key];
    if (localized) return localized;
    const parts = String(key).split('.');
    const raw = parts[parts.length - 1];
    return raw.replace(/([A-Z])/g, ' $1').replace(/^./, str => str.toUpperCase());
  }, [lang]);

  const translateThreatPattern = useCallback((pattern) => {
    if (!pattern) return '';
    const lower = pattern.toLowerCase();

    if (lower.includes('tld') || lower.includes('domain')) return t('threat.suspiciousTLD');
    if (lower.includes('shorten') || lower.includes('url')) return t('threat.shortenedURL');
    if (lower.includes('http')) return t('threat.httpLink');
    if (lower.includes('digital arrest') || lower.includes('police') || lower.includes('coercion')) return t('threat.digitalArrest');
    if (lower.includes('relative') || lower.includes('emergency') || lower.includes('distress')) return t('threat.emergencyFraud');
    if (lower.includes('otp') || lower.includes('credential') || lower.includes('extraction')) return t('threat.credentialTheft');
    if (lower.includes('remote') || lower.includes('anydesk') || lower.includes('teamviewer')) return t('threat.remoteDesktop');
    if (lower.includes('lottery') || lower.includes('kbc') || lower.includes('prize') || lower.includes('won')) return t('threat.lotteryScam');
    if (lower.includes('job') || lower.includes('task') || lower.includes('work-from-home')) return t('threat.jobScam');
    if (lower.includes('investment') || lower.includes('loan') || lower.includes('trading')) return t('threat.fakeInvestment');
    if (lower.includes('urgency') || lower.includes('blocked') || lower.includes('threat') || lower.includes('disconnect')) return t('threat.urgencyCoercion');
    if (lower.includes('refund') || lower.includes('over-refund') || lower.includes('accidental')) return t('threat.overRefund');
    if (lower.includes('upi') || lower.includes('untrusted') || lower.includes('unrecognized')) return t('threat.untrustedUPI');
    if (lower.includes('qr') || lower.includes('malformed')) return t('threat.malformedQR');
    if (lower.includes('voice') || lower.includes('clone') || lower.includes('deepfake')) return t('threat.voiceCloning');
    if (lower.includes('pitch') || lower.includes('monotone') || lower.includes('f0')) return t('threat.monotoneF0');
    if (lower.includes('gapless') || lower.includes('unnatural')) return t('threat.unnaturalSpeech');
    if (lower.includes('flat') || lower.includes('loudness')) return t('threat.flatLoudness');

    return pattern;
  }, [t]);

  const translateModuleTitle = useCallback((moduleTitle) => {
    if (!moduleTitle) return '';
    const lower = moduleTitle.toLowerCase();
    if (lower.includes('phishing')) return t('module.phishing');
    if (lower.includes('upi')) return t('module.upi');
    if (lower.includes('qr')) return t('module.qr');
    if (lower.includes('voice')) return t('module.voice');
    if (lower.includes('banking') || lower.includes('security')) return t('module.banking');
    return moduleTitle;
  }, [t]);

  return (
    <LanguageContext.Provider value={{ lang, changeLang, t, translateThreatPattern, translateModuleTitle, LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within a LanguageProvider');
  return ctx;
}
